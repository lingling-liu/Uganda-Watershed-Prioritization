import assert from 'node:assert/strict';
import fs from 'node:fs';
import {calculate,normalized,percentiles,scope,defaultFilters,withinTier,Indicator,Watershed} from '../src/engine';
const rows=JSON.parse(fs.readFileSync('public/data/watersheds.json','utf8')) as Watershed[];
const config=JSON.parse(fs.readFileSync('public/data/indicators.json','utf8')) as Indicator[];
const v=JSON.parse(fs.readFileSync('public/data/validation.json','utf8'));
const base=scope(rows,defaultFilters),ranked=calculate(base,config);
assert.equal(rows.length,2177);assert.equal(base.length,2028);assert.equal(config.length,21);
assert.equal(rows.filter(r=>r.hasGeometry).length,2135);assert.equal(config.filter(i=>i.include).length,7);
assert(Math.abs(Object.values(normalized(config)).reduce((a,b)=>a+b,0)-1)<1e-14);
for(const r of ranked)assert(Math.abs(r.score!-r.excelScore!)<1e-12,`Excel mismatch ${r.id}`);
assert.deepEqual(ranked.slice(0,5).map(r=>r.id),[1584,1649,1170,1585,1427]);
assert.equal(ranked[0].id,v.topFive[0].Lev12_ID);
const single=config.map(i=>({...i,include:i.id==='sed_export_per_ha',weight:1,direction:'higher' as const}));
const high=calculate(base,single),low=calculate(base,single.map(i=>({...i,direction:'lower'})));
const ix=new Map(low.map(r=>[r.id,r]));for(const r of high)assert(Math.abs(r.score!+ix.get(r.id)!.score!-1)<1e-12);
assert(high.some((r,i)=>r.id!==ranked[i].id),'Toggling criteria changes rank');
assert(calculate(base,config.map(i=>({...i,include:false}))).every(r=>r.score===null&&r.rank===null));
assert(calculate([base[0]],config).every(r=>r.score===null));assert.deepEqual(calculate([],config),[]);
assert.equal(percentiles([1,2,3,4]).get(2),.333);assert.equal(percentiles([0,0,1]).get(0),0);
const nullRow=rows.find(r=>r.raw.wyield_mn===null)!;assert(nullRow);assert(calculate([nullRow,base[0]],config).find(r=>r.id===nullRow.id)?.missing.includes('wyield_mn'));
assert.equal(ranked.filter(r=>withinTier(r,5,ranked.length)).length,Math.ceil(base.length*.05));
for(let j=1;j<ranked.length;j++){assert(ranked[j-1].score!>=ranked[j].score!);if(ranked[j-1].score===ranked[j].score){assert.equal(ranked[j-1].rank,ranked[j].rank);assert(ranked[j-1].id<ranked[j].id)}}
console.log('PASS: 2,177 records; 2,135 joins; 2,028 Excel scores; weight balance; directions; toggles; empty/singleton/zero weights; missing provenance; percentiles; deterministic ties.');
